#include "3-calc.h"

/**
	* op_add - adds a and b
	* @a: first int
	* @b: second int
	*
	* Return: the sum of a and b
	*/

int op_add(int a, int b)
{
	return (a + b);
}

/**
	* op_sub - calculates difference of a and b
	* @a: 1st int
	* @b: 2nd int
	*
	* Return: the difference of a and b
	*/

int op_sub(int a, int b)
{
	return (a - b);
}

/**
	* op_mul - calculates product of a and b
	* @a: 1st int
	* @b: 2nd int
	*
	* Return: the product of a and b
	*/

	int op_mul(int a, int b)
	{
			return (a * b);
	}

/**
	* op_mod - calculates the remainder of the division of a by b
	* @a: 1st int
	* @b: 2nd int
	*
	* Return: the the remainder of the division of a by b
	*/

int op_mod(int a, int b)
{
	return (a % b);
}

/**
	* op_div - calculates result of division of a by b
	* @a: 1st int
	* @b: 2nd int
	*
	* Return: the result of division of a by b
	*/

	int op_div(int a, int b)
	{
			return (a / b);
	}
